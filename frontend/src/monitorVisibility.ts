/**
 * 套利监控「当前」视图该不该显示某一行。
 *
 * 2026-09-02 运营者指着 LH2609−LH2703 那张卡:「这个过期了,就不要展示了」。
 *
 * `expired` 的含义是**先到期那条腿的散户可交易窗口,在最新快照日之前就已经关了**
 * (`days_to_window_end(最新快照日) == 0`)。这样的组合下不了单,而卡上照样写着
 * 「触发中 · 已拐头」「止损 −1360」「第一目标 −1225~−1080」—— 等于给一个买不进也
 * 卖不出的组合报价。
 *
 * **过期行里有两种,都得走**:
 *
 * 1. 今天刚关窗(`days_left == 0`,行是当天的)—— 数是新的,但已经不可交易;
 * 2. **早就关窗、行是旧快照**。窗口关掉之后这个组合不再进快照,接口于是把它
 *    **最后一次**的那一行接着往外发。2026-09-01 那天 94 行里有 23 行其实停在
 *    08-27 / 08-28,`days_left` 还写着「剩 2 日」—— 价差、位置、止损全是那一天的,
 *    却混在今天的列表里当当前行看。第 2 类比第 1 类更该藏:它连数都是过期的。
 *
 * **历史模式不滤**:那半边本来就是回看历年的进场日,那时的组合到今天当然都过期了,
 * 在那里滤掉等于把历史清空。它保持原样,带灰色「已过期」标(「历史信号」勾选框的
 * 说明里写着「过期组合带灰标」)。
 */
export function visibleItems<T extends { expired: boolean }>(
  items: readonly T[],
  historyMode: boolean
): T[] {
  return historyMode ? [...items] : items.filter((item) => !item.expired)
}
